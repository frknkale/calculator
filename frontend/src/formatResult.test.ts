import { describe, expect, it } from 'vitest';
import { formatResult } from './formatResult';

describe('formatResult', () => {
  it.each([
    ['0', '0'],
    ['-0', '0'],
    ['0.3000', '0.3'],
    ['1.2345678901234564', '1.2345678901234564'],
    ['1.23456789012345645', '1.2345678901234565'],
    ['-1.2345678901234565', '-1.2345678901234565'],
    ['9007199254740993', '9007199254740993'],
    ['1234567890123456.7', '1234567890123456.7'],
    ['1234567890.123456789', '1234567890.123456789'],
    ['123456789012345678', '123456789012345678'],
    ['1234567890123456789', '1234567890123456789'],
    ['-123456789012345678', '-123456789012345678'],
    ['999999999999999999.9', '999999999999999999.9'],
    ['9.9999999999999e99', '9.9999999999999e+99'],
    ['12345678901234567890', '12345678901234567890'],
    ['123456789012345678901', '1.23456789012346e+20'],
    ['-1234567890123456789', '-1234567890123456789'],
    ['-12345678901234567890', '-1.2345678901235e+19'],
    ['1234567890.123456789123', '1234567890.123456789'],
    ['99999999999999999999.9', '1e+20'],
    ['9.999999999999999e99', '1e+100'],
    ['1e+400', '1e+400'],
    ['1e-400', '1e-400'],
    ['10000000000000000000000000.2', '1e+25'],
    ['0.' + '0'.repeat(34) + '1', '1e-35'],
    ['-1e-16', '-1e-16'],
    ['0.0000001', '1e-7'],
    ['0.000001', '0.000001'],
    ['-0.000001', '-0.000001'],
    ['0.0000010001', '0.0000010001'],
    ['-0.0000010001', '-0.0000010001'],
    ['0.0000009999999999999', '9.999999999999e-7'],
    ['-0.0000009999999999999', '-9.999999999999e-7'],
    ['0.00000000000000003510176633732268465', '3.51017663373227e-17'],
    ['0.00000000000000011100153152096596185', '1.11001531520966e-16'],
    ['-0.123456789012345678', '-0.1234567890123457'],
    ['3.333333333333333e-101', '3.3333333333333e-101'],
  ])('formats %s as %s without Number conversion', (input, expected) => {
    expect(formatResult(input)).toBe(expected);
    expect(formatResult(input).length).toBeLessThanOrEqual(20);
  });
});
